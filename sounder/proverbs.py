def settings_of(settings: dict) -> dict:
    return settings.get("ai") or {}


def fixed_usage(p: tuple) -> str:
    """AI を使わないときの説明（一覧の意味）。"""
    return f"意味は、{p[2]}、ということです。"


def parts_of(p: tuple, usage: str, voice: str) -> list[dict]:
    """読み上げの並び（ことわざ → 使い方 → もう一度ことわざ）。"""
    return [{"text": f"今日のことわざです。{p[1]}。", "voice": voice},
            {"text": usage, "voice": voice},
            {"text": f"もう一度。{p[1]}。", "voice": voice}]


class Proverbs:
    def __init__(self, ai, path: Path, *, log=None) -> None:
        self.ai = ai                      # ai.AI（complete と設定を使う）
        self.path = path                  # 次に読む番号と、どの回にどれを割り当てたかを覚えておくファイル
        self._log = log or (lambda *a, **k: None)
        self._lock = threading.Lock()
        self._done: dict[int, str] = {}   # ことわざの番号 → AI が作った使い方
        self._busy: set[int] = set()
        self._memory: dict | None = None

    def _mem(self) -> dict:
        if self._memory is None:
            try:
                self._memory = json.loads(self.path.read_text("utf-8"))
            except (OSError, ValueError):
                self._memory = {}
        return self._memory

    def _save(self) -> None:
        try:
            tmp = self.path.with_suffix(".tmp")
            tmp.write_text(json.dumps(self._mem(), ensure_ascii=False), "utf-8")
            os.replace(tmp, self.path)
        except OSError:
            pass

    def index_for(self, key: str | None) -> int:
        """その回のことわざの番号。初めての回なら次の番号を割り当てる。key が無い（試聴）なら次の番号を見るだけ。"""
        with self._lock:
            mem = self._mem()
            nxt = int(mem.get("next") or 0) % len(PROVERBS)
            if key is None:
                return nxt
            assigned = mem.setdefault("assigned", {})
            if key in assigned:
                return int(assigned[key]) % len(PROVERBS)
            assigned[key] = nxt
            mem["assigned"] = dict(list(assigned.items())[-KEEP_ASSIGNED:])
            mem["next"] = (nxt + 1) % len(PROVERBS)
            self._save()
            return nxt

    def get(self, settings: dict, key: str | None, voice: str) -> list[dict]:
        """続けて読む「今日のことわざ」。AI の答えがまだなら作り始めて、一覧の意味で読む。"""
        i = self.index_for(key)
        p = PROVERBS[i]
        usage = None
        if self.ai and settings_of(settings).get("enabled"):
            with self._lock:
                usage = self._done.get(i)
                start = usage is None and i not in self._busy
                if start:
                    self._busy.add(i)
            if start:
                threading.Thread(target=self._generate, args=(settings, i),
                                 name="proverb", daemon=True).start()
        return parts_of(p, usage or fixed_usage(p), voice)

    @staticmethod
    def prompt(p: tuple) -> str:
        return "\n".join([
            "家のスピーカーで、予定のお知らせのあとに「今日のことわざ」を読み上げます。"
            "聞くのはカナダに住む日本人の家族で、小学生の子どももいます。",
            f"今日のことわざ: {p[0]}（{p[1]}）",
            f"意味: {p[2]}",
            "usage には、このことわざの意味をやさしく一言で言ってから、どんなときに使うかを、"
            "学校や家でありそうな場面の例と、その場面で実際に言うせりふ 1 つで説明する文を入れてください。"
            "ことわざそのものは、このあと別に読むので、usage の中では「このことわざ」と言い換えてかまいません。"
            "せりふの中でことわざを言うときは、ひらがなで書く（読み間違えないように）。"
            "子どもにも分かるやさしい日本語の話し言葉で、記号・絵文字・かっこ書きは使わない。150字くらいまで。",
            '{"usage": "…"} の JSON だけを出力してください。前置きやコードブロックは付けない。',
        ])

    @staticmethod
    def parse(text: str) -> str:
        i, j = text.find("{"), text.rfind("}")
        if i < 0 or j <= i:
            raise ValueError("JSON がありません")
        usage = json.loads(text[i:j + 1]).get("usage")
        if not isinstance(usage, str) or not usage.strip():
            raise ValueError("usage がありません")
        return usage.strip()[:400]

    def _generate(self, settings: dict, i: int) -> None:
        t = time.time()
        try:
            usage = self.parse(self.ai.complete(settings, self.prompt(PROVERBS[i]), max_tokens=800))
            self._log("info", f"AI が今日のことわざ「{PROVERBS[i][0]}」の使い方を作りました（{time.time() - t:.1f} 秒）")
        except Exception as exc:   # AI が使えなくても、一覧の意味を読めばよい
            usage = ""
            self._log("error", f"AI でことわざの使い方を作れなかったので、決まった文で読みます（{exc}）")
        with self._lock:
            # 作れなかったときも空で覚えて、同じことわざで何度も頼み直さない
            self._done = {k: v for k, v in list(self._done.items())[-20:]}
            self._done[i] = usage
            self._busy.discard(i)
